'use strict';
const fs=require('fs');
const assert=require('assert');
const workflow=fs.readFileSync('.github/workflows/audit-regression.yml','utf8');
const runner=fs.readFileSync('scripts/run-nightly-audit.mjs','utf8');
assert(workflow.includes("cron: '0 21 * * *'"),'Auditoria técnica deve rodar às 18:00 de Brasília (21:00 UTC)');
assert(workflow.includes('workflow_dispatch:'),'Auditoria técnica deve permitir disparo manual controlado');
assert(workflow.includes("[nightly-audit-now]"),'Workflow deve permitir disparo por marcador técnico sem rodar bateria completa em todo push');
assert(workflow.includes("contains(github.event.head_commit.message, '[nightly-audit-now]')"),'Gatilho técnico deve depender explicitamente do marcador no commit');
assert(workflow.includes('node scripts/run-nightly-audit.mjs'),'Workflow deve gerar o relatório sanitizado');
assert(workflow.includes('auditor-nightly-data'),'Workflow deve publicar o último relatório técnico');
assert(workflow.includes('if: always()'),'Publicação do relatório deve ocorrer mesmo quando a auditoria encontra regressões');
assert(runner.includes("/^audit-.*\\.cjs$/i")||runner.includes("startsWith('audit-')"),'Runner deve descobrir a biblioteca audit-*');
assert(runner.includes('latest.json'),'Runner deve gerar latest.json');
console.log('OK nightly schedule regression: 18h + manual marker + publicação mesmo com falhas');
