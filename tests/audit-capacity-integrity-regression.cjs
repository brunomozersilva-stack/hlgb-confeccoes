const fs=require('fs'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync(require('path').join(__dirname,'..','release-capacity-integrity.js'),'utf8');
const auto1={id:1,orderId:10,itemKey:'P1',locationId:20,qty:420,date:'2026-09-07',source:'cut_assignment'};
const auto2={...auto1,id:2};
const autoDifferentQty={...auto1,id:3,qty:200};
const manual1={id:4,orderId:10,itemKey:'P1',locationId:20,qty:420,date:'2026-09-07',source:'capacity_queue_v9140'};
const manual2={...manual1,id:5};
const db={capacityAssignments:[auto1,auto2,autoDifferentQty,manual1,manual2]};
let saveCalls=0,persistCalls=0,renderCalls=0,incomingCalls=0;
const window={db,save(){saveCalls++;return db.capacityAssignments.length},persistDb(){persistCalls++;return true},renderCapacityPlanning(){renderCalls++;return db.capacityAssignments.length},hlgbRenderIncomingRecord(){incomingCalls++;return true}};
const ctx=vm.createContext({db,window,console,setTimeout(){},hlgbAfterLogin(){}});vm.runInContext(src,ctx);
const canonical=window.hlgbCanonicalCapacityAssignments([auto1,auto2,autoDifferentQty,manual1,manual2]);
assert.deepEqual(canonical.map(x=>x.id),[1,3,4,5],'only exact cut_assignment duplicate must be removed; manual/split rows stay');
db.capacityAssignments=[auto1,auto2,autoDifferentQty,manual1,manual2];
window.save();
assert.equal(saveCalls,1);assert.deepEqual(db.capacityAssignments.map(x=>x.id),[1,3,4,5],'duplicate auto capacity must be removed before save');
db.capacityAssignments.push({...auto1,id:6});
window.persistDb();
assert.equal(persistCalls,1);assert.deepEqual(db.capacityAssignments.map(x=>x.id),[1,3,4,5],'duplicate auto capacity must be removed before persistDb');
db.capacityAssignments.push({...auto1,id:7});
window.hlgbRenderIncomingRecord('capacityAssignments');
assert.equal(incomingCalls,1);assert.deepEqual(db.capacityAssignments.map(x=>x.id),[1,3,4,5],'incoming duplicate must be collapsed locally');
assert.equal(window.HLGB_CAPACITY_INTEGRITY_GUARD,'v1');
console.log('PASS capacity integrity: exact automatic duplicate is collapsed before save/render; manual and split assignments remain.');