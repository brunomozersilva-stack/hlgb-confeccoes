'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const text=fs.readFileSync('release-auditor-autocorrect-v9448.js','utf8');
const start=text.indexOf('function flagUnstableProduction9571(');
const end=text.indexOf('\nasync function run(opts={}){',start);
assert(start>=0&&end>start,'Auditor must expose record-level convergence proof');
const ctx={sid:x=>String(x??'')};
const fn=vm.runInNewContext(text.slice(start,end)+'\nflagUnstableProduction9571',ctx);
const proof={id:'1793126491713',module:'production',action:'production-reconcile',operationIds:['op-1']};
const incomplete={fixed:1,corrected:[proof],stillFailing:[{id:proof.id,action:'production-reconcile',classification:'needs-code'}],unverified:[]};
const flagged=fn(incomplete);
assert.equal(flagged.fixed,0,'partial correction must not inflate fixed count');
assert.equal(flagged.corrected.length,0);
assert.equal(flagged.partialCorrections.length,1);
assert.equal(flagged.partialCorrections[0].operationIds[0],'op-1','keep actual remote proof');
assert.equal(flagged.recordConvergenceVerified,false);
const complete={fixed:1,corrected:[proof],stillFailing:[],unverified:[]};
assert.equal(fn(complete).fixed,1,'fully resolved correction stays counted');
const mixed={fixed:2,corrected:[proof,{id:'other',module:'cuts'}],unverified:[{id:proof.id,action:'production-reconcile'}]};
assert.equal(fn(mixed).fixed,1,'unrelated corrected record stays fixed');
assert.equal(mixed.corrected.length,1);
console.log('PASS v95.71: Auditor reports partial verified opId without claiming production record converged.');
