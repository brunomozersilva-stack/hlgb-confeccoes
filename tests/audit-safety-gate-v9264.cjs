const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const root=path.join(__dirname,'..');
const src=f=>fs.readFileSync(path.join(root,f),'utf8');
const gateFile='release-safety-gate-v9268.js';
for(const f of [gateFile,'hlgb-canonical-sw.js','release-safari-resume-v9266.js'])assert.doesNotThrow(()=>new vm.Script(src(f),{filename:f}),f+' deve compilar');
const manifest=JSON.parse(src('release.json'));
assert.equal(manifest.version,'92.68');
assert.equal(manifest.minimum_version,'92.68');
assert.equal(manifest.entry,'app-stable3.html');
assert.equal(manifest.force_canonical,true);
const loader=src('app-stable3.html');
assert(loader.includes("navigator.serviceWorker.register('./hlgb-canonical-sw.js'"),'loader deve registrar service worker canônico');
assert(loader.includes("'release-assistant-brain-v9265.js','release-hub-editor-v9267.js','release-assistant-ui-v9267.js','release-assistant-studio-v9268.js','release-safety-gate-v9268.js','release-ui-stability.js','release-safari-resume-v9266.js'"),'brain local, Hub editor, Studio, safety gate e guarda Safari devem carregar em ordem segura');
assert(!loader.includes("'release-assistant-server-v9266.js'"),'modo gratuito não deve carregar IA de servidor');
assert(loader.lastIndexOf("'release-safari-resume-v9266.js'")>loader.lastIndexOf("'release-ui-stability.js'"),'guarda Safari deve carregar depois da estabilidade visual');
assert(loader.lastIndexOf("'release-ui-stability.js'")>loader.lastIndexOf("'release-safety-gate-v9268.js'"),'estabilidade deve carregar depois do safety gate');
for(const f of ['app-stable.html','app-stable2.html'])assert(src(f).includes('app-stable3.html?reroute='),f+' deve redirecionar para stable3');
const sw=src('hlgb-canonical-sw.js');
assert(sw.includes("req.mode!=='navigate'"),'SW não deve interceptar fetch interno da base');
assert(sw.includes("/^app\\d+\\.html$/"),'SW deve reconhecer páginas numeradas antigas');
const gate=src(gateFile);
assert(gate.includes("const V='92.68'"),'safety gate deve marcar v92.68');
assert(gate.includes('HLGB_AUDIT_READ_ONLY_ACTIVE'),'Auditor deve ativar modo somente leitura real');
assert(gate.includes("m!=='systemAuditRuns'"),'histórico técnico do auditor pode ser salvo');
assert(gate.includes("'hlgbRecordSaveWithRetry'"),'gravação operacional deve ser protegida');
assert(gate.includes("'hlgbAuditorRunVisualSweep'"),'varredura visual deve rodar sob trava');
assert(gate.includes('HLGB_PAID_AI_DISABLED=true'),'modo sem custo deve ficar travado no safety gate');
console.log('PASS v92.68: versão canônica, reroute, IA local sem custo, auditor somente leitura e guarda Safari validados.');
