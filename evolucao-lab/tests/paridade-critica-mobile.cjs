'use strict';
const assert=require('node:assert/strict'),http=require('node:http'),fs=require('node:fs'),path=require('node:path'),{chromium,webkit}=require('playwright');
const browserType=process.env.HLGB_BROWSER==='webkit'?webkit:chromium;
const source=fs.readFileSync(path.resolve(__dirname,'..','paridade-critica.html'),'utf8');
const server=http.createServer((req,res)=>{res.writeHead(200,{'content-type':'text/html;charset=utf-8','cache-control':'no-store'});res.end(source);});
(async()=>{
 await new Promise(ok=>server.listen(0,'127.0.0.1',ok));const browser=await browserType.launch();
 try{const context=await browser.newContext({viewport:{width:390,height:820},acceptDownloads:true});const page=await context.newPage(),errors=[];
 page.on('pageerror',x=>errors.push(x.message));
 await page.goto('http://127.0.0.1:'+server.address().port+'/');await page.locator('[data-review-id="DET-001"][data-review-field=desktop]').selectOption('passou');
 await page.locator('[data-review-id="DET-001"][data-review-field=mobile]').selectOption('falhou');
 await page.locator('[data-review-id="DET-001"][data-review-field=note]').fill('Botão ilustrativo não acessível no mobile fictício');
 await page.locator('#q').fill('travetada');assert.ok((await page.locator('.case').count())<43);
 await page.locator('#q').fill('');
 assert.equal(await page.locator('[data-review-id="DET-001"][data-review-field=desktop]').inputValue(),'passou');
 assert.equal(await page.locator('[data-review-id="DET-001"][data-review-field=mobile]').inputValue(),'falhou');
 assert.match(await page.locator('#review-summary').innerText(),/1 de 43/);
 const downloadPromise=page.waitForEvent('download');await page.locator('#review-export').click();const download=await downloadPromise;
 assert.match(download.suggestedFilename(),/\.json$/);
 const file=await download.path(),saved=JSON.parse(fs.readFileSync(file,'utf8'));
 assert.equal(saved.scenarios.length,43);
 assert.equal(saved.productionApproval,false);assert.equal(saved.approvedForRemoval,false);
 const entry=saved.scenarios.find(x=>x.id==='DET-001');assert.equal(entry.desktop,'passou');assert.equal(entry.mobile,'falhou');
 assert.equal(entry.formalApproval,false);assert.match(entry.note,/Botão ilustrativo/);
 assert.equal(saved.scenarios.find(x=>x.id==='DET-043').desktop,'nao_testado');
 await page.reload();assert.equal(await page.locator('[data-review-id="DET-001"][data-review-field=desktop]').inputValue(),'nao_testado');
 assert.deepEqual(errors,[]);
 await context.close();console.log('Homologação manual simulada aprovada no navegador '+browserType.name());
 }finally{await browser.close();await new Promise(ok=>server.close(ok));}
})().catch(e=>{console.error(e);process.exitCode=1});
