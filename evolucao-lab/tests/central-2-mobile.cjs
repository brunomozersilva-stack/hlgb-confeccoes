'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),{pathToFileURL}=require('node:url');
const {chromium,webkit}=require('playwright');
const browserType=process.env.HLGB_BROWSER==='webkit'?webkit:chromium;
const pageURL=pathToFileURL(path.resolve(__dirname,'../central-operacional-2.html')).href;
const out=process.env.HLGB_SCREENSHOT_DIR||'/tmp';
async function run(browser,width){
 const page=await browser.newPage({viewport:{width,height:860},deviceScaleFactor:1,acceptDownloads:true});
 const errors=[],requests=[];
 page.on('pageerror',e=>errors.push(String(e.message||e)));
 page.on('request',r=>{if(/^https?:/i.test(r.url()))requests.push(r.url())});
 const nav=key=>page.locator(width<=670?'#mobile-nav [data-view="'+key+'"]':'#sidebar-nav [data-view="'+key+'"]');
 const row=(id)=>page.locator('#acertos-body tr').filter({hasText:id});
 const card=(id)=>page.locator('#acertos-mobile .mobile-card').filter({hasText:id});
 async function choose(id){
  if(width<=670)await card(id).locator('input[type="checkbox"]').check();
  else await row(id).locator('input[type="checkbox"]').check();
 }
 try{
  await page.goto(pageURL,{waitUntil:'load'});
  assert.match(await page.locator('#page-title').innerText(),/Seu dia/);
  assert.equal((await page.locator('#metric-hub').innerText()).trim(),'2');
  assert.equal(await page.locator('#overview-tasks .mobile-card').count(),5);
  await nav('acertos').click();
  assert.equal(await page.locator('#acertos-body tr').count(),8);
  await page.locator('#acerto-search').fill('Roseli');
  assert.equal(await page.locator('#acertos-body tr').count(),2);
  await page.locator('#acerto-search').fill('');
  await page.locator('#acerto-status').selectOption('Pendente');
  assert.equal(await page.locator('#acertos-body tr').count(),6);
  await page.locator('#acerto-status').selectOption('all');
  const editButton=width<=670?card('AC-1041').locator('button[data-edit]'):row('AC-1041').locator('button[data-edit]');
  await editButton.click();
  assert.equal(await page.locator('#record-dialog').evaluate(e=>e.open),true);
  await page.locator('#edit-qty').fill('200');
  await page.locator('#edit-price').fill('0,80');
  await page.locator('#edit-discount').fill('0,05');
  assert.match(await page.locator('#edit-preview').innerText(),/150,00/);
  await page.locator('#modal-save').click();
  assert.equal(await page.locator('#record-dialog').evaluate(e=>e.open),false);
  assert.match(await row('AC-1041').innerText(),/150,00/);
  await page.locator('#new-record').click();
  await page.locator('#edit-model').fill('Conjunto Paula');
  await page.locator('#edit-faction').selectOption('Fran');
  await page.locator('#edit-qty').fill('40');
  await page.locator('#edit-price').fill('0,50');
  await page.locator('#edit-discount').fill('0,05');
  await page.locator('#edit-extra').fill('-1,00');
  await page.locator('#edit-reason').fill('Conferência de peças');
  assert.match(await page.locator('#edit-preview').innerText(),/17,00/);
  await page.locator('#modal-save').click();
  assert.match(await row('AC-1043').innerText(),/17,00/);
  await choose('AC-1042');await choose('AC-1041');
  assert.match(await page.locator('#bulk-count').innerText(),/2 selecionado/);
  await page.locator('#bulk-pay').click();
  assert.match(await page.locator('#pay-message').innerText(),/2 acerto/);
  assert.match(await page.locator('#pay-total').innerText(),/250,80/);
  await page.locator('#pay-confirm').click();
  assert.equal((await page.locator('#metric-hub').innerText()).trim(),'4');
  assert.match(await row('AC-1042').innerText(),/Pago/);
  assert.match(await row('AC-1041').innerText(),/Pago/);
  await nav('hub').click();
  assert.equal(await page.locator('#hub-body tr').count(),4);
  await page.locator('#hub-period').selectOption('session');
  assert.equal(await page.locator('#hub-body tr').count(),2);
  await page.locator('#hub-search').fill('1041');
  assert.equal(await page.locator('#hub-body tr').count(),1);
  await page.locator('#hub-search').fill('');
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#hub-export').click()]);
  assert.match(download.suggestedFilename(),/hub-ficticio-evolucao\.csv/);
  const [evidenceDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#hub-evidence').click()]);
  assert.equal(evidenceDownload.suggestedFilename(),'HLGB-EVOLUCAO-TESTE-FICTICIO.json');
  const evidence=JSON.parse(fs.readFileSync(await evidenceDownload.path(),'utf8'));
  assert.equal(evidence.schema,'hlgb-evolucao-teste-operacional-v1');
  assert.equal(evidence.environment,'offline-demo');
  assert.equal(evidence.fictitious,true);
  assert.equal(evidence.productionApproval,false);
  assert.equal(evidence.counts.acertos,9);
  assert.equal(evidence.counts.hub,4);
  assert.equal(evidence.counts.paid,4);
  assert.equal(evidence.checks.hubSemDuplicacao,true);
  assert.equal(evidence.checks.acertosPagosComLancamento,true);
  assert.equal(evidence.checks.valoresEmCentavosInteiros,true);
  assert(evidence.historico.some(e=>/pago/i.test(e.message)));
  await nav('faccoes').click();
  assert.equal(await page.locator('#faction-cards .fac-card').count(),7);
  assert.equal(await page.locator('#service-cards .fac-card').count(),3);
  const original=await page.locator('#route-list li').nth(5).innerText();
  assert.match(original,/Roseli/);
  await page.locator('button[data-move="5:-1"]').click();
  assert.match(await page.locator('#route-list li').nth(4).innerText(),/Roseli/);
  await page.locator('#faction-cards').getByRole('button',{name:'Ver acertos'}).first().click();
  assert.match(await page.locator('#page-title').innerText(),/Acertos/);
  await page.locator('#acerto-search').fill('');
  // Um serviço avulso fictício de embalagem deve usar apenas embaladeiras e sugerir preço editável.
  await page.locator('#new-record').click();
  await page.locator('#edit-service').selectOption('Embalagem');
  assert.equal(await page.locator('#edit-faction option').count(),2);
  assert.equal(await page.locator('#edit-faction').inputValue(),'Embaladeira Demo A');
  assert.equal(await page.locator('#edit-discount').isDisabled(),true);
  await page.locator('#edit-model').fill('Camisola Melina');
  await page.locator('#edit-model').press('Tab');
  assert.equal(await page.locator('#edit-price').inputValue(),'0,25');
  await page.locator('#edit-qty').fill('20');
  assert.match(await page.locator('#edit-preview').innerText(),/5,00/);
  await page.locator('#edit-extra').fill('-1,00');
  await page.locator('#edit-reason').fill('Teste de embalagem fictício');
  assert.match(await page.locator('#edit-preview').innerText(),/4,00/);
  await page.locator('#modal-save').click();
  await page.locator('#acerto-service').selectOption('Embalagem');
  assert.equal(await page.locator('#acertos-body tr').count(),1);
  assert.match(await row('AC-1044').innerText(),/Embaladeira Demo A/);
  await page.locator('#acerto-service').selectOption('all');

  const avulsoPay=width<=670?card('AC-1044').locator('button[data-pay]'):row('AC-1044').locator('button[data-pay]');
  await avulsoPay.click();
  await page.locator('#pay-proof').setInputFiles({name:'comprovante-ficticio.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\\n%%EOF\\n')});
  await page.locator('#pay-confirm').click();
  assert.equal((await page.locator('#metric-hub').innerText()).trim(),'5');
  assert.match(await row('AC-1044').innerText(),/Pago/);
  await nav('hub').click();
  assert.match(await page.locator('#hub-body').innerText(),/PDF fictício: comprovante-ficticio.pdf/);
  const [extraEvidence]=await Promise.all([page.waitForEvent('download'),page.locator('#hub-evidence').click()]);
  const avulsoReport=JSON.parse(fs.readFileSync(await extraEvidence.path(),'utf8'));
  assert.equal(avulsoReport.counts.hub,5);
  assert.equal(avulsoReport.checks.acertosPagosComLancamento,true);
  assert.equal(avulsoReport.hub.find(h=>h.source==='AC-1044').service,'Embalagem');

  // Uma travetadora fictícia aparece somente para o serviço de travetada.
  await nav('acertos').click();
  await page.locator('#new-record').click();
  await page.locator('#edit-service').selectOption('Travetada');
  assert.equal(await page.locator('#edit-faction option').count(),1);
  assert.equal(await page.locator('#edit-faction').inputValue(),'Travetadora Demo A');
  await page.locator('#edit-model').fill('Calcinha Tammy');
  await page.locator('#edit-model').press('Tab');
  assert.equal(await page.locator('#edit-price').inputValue(),'0,06');
  await page.locator('#edit-qty').fill('10');
  assert.match(await page.locator('#edit-preview').innerText(),/0,60/);
  await page.locator('#modal-save').click();
  await page.locator('#acerto-service').selectOption('Travetada');
  assert.equal(await page.locator('#acertos-body tr').count(),1);
  assert.match(await row('AC-1045').innerText(),/Travetadora Demo A/);
  await page.locator('#acerto-service').selectOption('all');

  // Devoluções em acerto pendente mantêm o lançamento e registram quantidade anterior.
  const returnButton=width<=670?card('AC-1039').locator('button[data-return]'):row('AC-1039').locator('button[data-return]');
  await returnButton.click();
  assert.match(await page.locator('#return-context').innerText(),/350 peças/);
  await page.locator('#return-qty').fill('350');
  await page.locator('#return-reason').fill('Devolução demonstrativa conferida');
  assert.equal(await page.locator('#return-confirm').isDisabled(),true);
  await page.locator('#return-qty').fill('20');
  assert.match(await page.locator('#return-preview').innerText(),/79,20/);
  await page.locator('#return-confirm').click();
  assert.match(await row('AC-1039').innerText(),/330/);
  assert.match(await row('AC-1039').innerText(),/79,20/);
  const pendingHistory=width<=670?card('AC-1039').locator('button[data-history]'):row('AC-1039').locator('button[data-history]');
  await pendingHistory.click();
  assert.match(await page.locator('#history-list').innerText(),/Devolução de peças/);
  assert.match(await page.locator('#history-list').innerText(),/Antes: 350 peças/);
  await page.locator('#history-close').click();

  // Um acerto já pago não pode ser editado nem ter o pagamento original sobrescrito.
  const paid=width<=670?card('AC-1041'):row('AC-1041');
  await paid.locator('button[data-edit]').click();
  assert.equal(await page.locator('#modal-save').isHidden(),true);
  await page.locator('#modal-cancel').click();
  await paid.locator('button[data-correction]').click();
  await page.locator('#correction-amount').fill('151,00');
  await page.locator('#correction-reason').fill('Devolução financeira fictícia');
  assert.equal(await page.locator('#correction-confirm').isDisabled(),true);
  await page.locator('#correction-amount').fill('25,00');
  assert.match(await page.locator('#correction-preview').innerText(),/125,00/);
  await page.locator('#correction-confirm').click();
  assert.match(await row('AC-1041').innerText(),/150,00/);
  await nav('hub').click();
  assert.equal(await page.locator('#hub-body tr').count(),6);
  assert.match(await page.locator('#hub-body').innerText(),/Compensação/);
  const [finalEvidence]=await Promise.all([page.waitForEvent('download'),page.locator('#hub-evidence').click()]);
  const finalReport=JSON.parse(fs.readFileSync(await finalEvidence.path(),'utf8'));
  const originalPayment=finalReport.hub.find(h=>h.source==='AC-1041'&&h.type!=='correcao');
  const correction=finalReport.hub.find(h=>h.source==='AC-1041'&&h.type==='correcao');
  assert.equal(originalPayment.amount,15000);
  assert.equal(correction.amount,-2500);
  assert.equal(correction.operationKey,'COR-AC-1041-1');
  assert.equal(finalReport.checks.hubSemDuplicacao,true);
  assert.equal(finalReport.checks.pagamentosOriginaisSemDuplicacao,true);
  assert.equal(finalReport.checks.acertosPagosComLancamento,true);
  assert.equal(finalReport.checks.compensacoesDentroDoSaldo,true);
  assert.equal(finalReport.historicoPorAcerto['AC-1039'].at(-1).event,'Devolução de peças');
  assert.equal(finalReport.historicoPorAcerto['AC-1041'].at(-1).event,'Compensação após pagamento');
  assert.equal(finalReport.acertos.find(x=>x.id==='AC-1039').qty,330);
  await nav('acertos').click();
  const corrected=width<=670?card('AC-1041'):row('AC-1041');
  await corrected.locator('button[data-history]').click();
  assert.match(await page.locator('#history-list').innerText(),/Compensação após pagamento/);
  assert.match(await page.locator('#history-list').innerText(),/Pagamento simulado/);
  await page.locator('#history-close').click();

  await page.locator('#reset-demo').click();
  assert.equal(await page.locator('#acertos-body tr').count(),8);
  assert.equal((await page.locator('#metric-hub').innerText()).trim(),'2');
  const dims=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert(dims.scroll<=dims.width+2,'overflow '+width+' '+JSON.stringify(dims));
  assert.deepEqual(errors,[],'browser errors');
  assert.deepEqual(requests,[],'no external calls');
  if(width===375){
   fs.mkdirSync(out,{recursive:true});
   await page.screenshot({path:path.join(out,'central-operacional-2-'+browserType.name()+'-375.png'),fullPage:true});
  }
  console.log('PASS Central 2.0 '+browserType.name()+' '+width+'px · edição, avulsos, devolução, compensação, histórico, Hub e mobile');
 }finally{await page.close()}
}
(async()=>{
 const browser=await browserType.launch({headless:true});
 try{for(const w of [320,375,390,768,1280])await run(browser,w)}finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
