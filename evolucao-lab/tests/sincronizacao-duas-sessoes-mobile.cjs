'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url'),{chromium,webkit}=require('playwright');
const type=process.env.HLGB_BROWSER==='webkit'?webkit:chromium;
const target=pathToFileURL(path.resolve(__dirname,'../sincronizacao-duas-sessoes.html')).href;
const shots=process.env.HLGB_SCREENSHOT_DIR||'/tmp/hlgb-sessoes';
async function testPage(browser,width){
 const page=await browser.newPage({viewport:{width,height:810},deviceScaleFactor:1,acceptDownloads:true});
 const errors=[],remote=[];page.on('pageerror',e=>errors.push(String(e.message||e)));
 page.on('request',r=>{if(/^https?:/i.test(r.url()))remote.push(r.url())});
 const click=(id,action)=>page.locator('button[data-id="'+id+'"][data-action="'+action+'"]').click();
 const txt=id=>page.locator('#'+id).innerText();
 try{
  await page.goto(target,{waitUntil:'load'});
  assert.match(await txt('server-amount'),/100,00/);
  assert.equal((await txt('server-revision')).trim(),'1');
  assert.equal((await txt('server-events')).trim(),'0');
  assert.equal((await txt('pending-count')).trim(),'0');
  await page.locator('[data-scenario="success"]').click();
  assert.match(await txt('server-amount'),/120,00/);
  assert.equal((await txt('server-revision')).trim(),'2');
  assert.equal((await txt('seen-rev-B')).trim(),'2');
  assert.match(await txt('message-A'),/Salvo e confirmado por releitura/);
  assert.equal((await txt('server-events')).trim(),'1');
  await page.locator('[data-scenario="lostack"]').click();
  assert.match(await txt('server-amount'),/125,00/);
  assert.match(await txt('seen-value-A'),/100,00/);
  assert.match(await txt('message-A'),/Inconclusivo/);
  assert.equal((await txt('pending-count')).trim(),'1');
  assert.equal(await page.locator('button[data-id="A"][data-action="save"]').isDisabled(),true);
  await click('A','reconcile');
  assert.match(await txt('message-A'),/Salvo e confirmado/);
  assert.equal((await txt('pending-count')).trim(),'0');
  assert.equal((await txt('server-events')).trim(),'1');
  await page.locator('[data-scenario="conflict"]').click();
  assert.match(await txt('server-amount'),/150,00/);
  assert.match(await txt('draft-A'),/110,00/);
  assert.match(await txt('message-A'),/CONFLITO/);
  assert.equal((await txt('pending-count')).trim(),'1');
  await click('A','review');
  assert.match(await txt('draft-A'),/110,00/);
  assert.match(await txt('seen-value-A'),/150,00/);
  assert.equal((await txt('pending-count')).trim(),'0');
  await click('A','refresh');
  assert.match(await txt('message-A'),/bloqueada para não perder seu rascunho/);
  assert.match(await txt('draft-A'),/110,00/);
  await click('A','save');
  assert.equal((await txt('server-revision')).trim(),'3');
  assert.match(await txt('server-amount'),/110,00/);
  assert.equal((await txt('server-events')).trim(),'2');
  assert.match(await txt('seen-value-B'),/150,00/);
  await click('B','refresh');
  assert.match(await txt('seen-value-B'),/110,00/);
  await page.locator('[data-scenario="notfound"]').click();
  assert.equal((await txt('server-events')).trim(),'0');
  assert.match(await txt('pending-A'),/not_found/);
  assert.equal(await page.locator('button[data-id="A"][data-action="retry"]').isEnabled(),true);
  await click('A','retry');
  assert.match(await txt('server-amount'),/130,00/);
  assert.equal((await txt('server-revision')).trim(),'2');
  assert.equal((await txt('server-events')).trim(),'1');
  await page.locator('[data-scenario="readback"]').click();
  assert.match(await txt('message-A'),/Inconclusivo/);
  await click('A','reconcile');
  assert.match(await txt('message-A'),/Salvo e confirmado/);
  assert.match(await txt('server-amount'),/145,00/);
  // Simular uma fila exclusivamente em memória; só transmitir após reconectar manualmente.
  await page.locator('#reset-all').click();
  await click('A','toggle');
  assert.match(await txt('online-A'),/Desconectada/);
  await page.locator('#value-A').fill('180,00');
  await click('A','save');
  assert.match(await txt('message-A'),/Na fila de memória/);
  assert.equal((await txt('server-events')).trim(),'0');
  assert.equal((await txt('pending-count')).trim(),'1');
  await click('A','toggle');
  assert.equal((await txt('server-events')).trim(),'0','reconnect must not auto-send');
  await click('A','deliver');
  assert.match(await txt('server-amount'),/180,00/);
  assert.equal((await txt('server-events')).trim(),'1');
  assert.equal((await txt('pending-count')).trim(),'0');
  assert.match(await txt('seen-value-B'),/100,00/);
  await click('B','refresh');
  assert.match(await txt('seen-value-B'),/180,00/);
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export-evidence').click()]);
  assert.equal(download.suggestedFilename(),'HLGB-EVOLUCAO-DUAS-SESSOES-FICTICIO.json');
  const report=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
  assert.equal(report.schema,'hlgb-evolucao-duas-sessoes-v1');
  assert.equal(report.environment,'in-memory-offline');
  assert.equal(report.productionApproval,false);
  assert.equal(report.realBrowserSyncTested,false);
  assert.equal(report.state.server.events.length,1);
  assert.equal(report.state.server.record.amountCents,18000);
  assert(Object.values(report.checks).every(Boolean));
  const dims=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert(dims.scroll<=dims.width+2,'horizontal overflow '+width+': '+JSON.stringify(dims));
  assert.deepEqual(errors,[],'JS errors');assert.deepEqual(remote,[],'no external network');
  if(width===375){fs.mkdirSync(shots,{recursive:true});await page.screenshot({path:path.join(shots,'duas-sessoes-'+type.name()+'-375.png'),fullPage:true})}
  console.log('PASS duas sessões '+type.name()+' '+width+'px: 5 cenários, offline, conflitos, ACK, readback, export e integridade');
 }finally{await page.close()}
}
(async()=>{const browser=await type.launch({headless:true});try{for(const w of [320,375,390,768,1280])await testPage(browser,w)}finally{await browser.close()}})().catch(e=>{console.error(e);process.exitCode=1});
