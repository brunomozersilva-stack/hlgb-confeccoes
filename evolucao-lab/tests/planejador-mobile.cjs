'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url'),{chromium,webkit}=require('playwright');
const engine=process.env.HLGB_BROWSER==='webkit'?webkit:chromium;
const url=pathToFileURL(path.resolve(__dirname,'../planejador-materiais.html')).href;
const out=process.env.HLGB_SCREENSHOT_DIR||'/tmp/hlgb-materiais';
async function run(browser,width){
 const page=await browser.newPage({viewport:{width,height:820},deviceScaleFactor:1,acceptDownloads:true});
 const errors=[],requests=[];
 page.on('pageerror',e=>errors.push(String(e.message||e)));
 page.on('request',r=>{if(/^https?:/i.test(r.url()))requests.push(r.url())});
 const tab=name=>page.locator('[data-tab="'+name+'"]');
 const money=async name=>(await page.locator('#metric-'+name).innerText()).trim();
 try{
  await page.goto(url,{waitUntil:'load'});
  assert.equal((await page.locator('#metric-models').innerText()).trim(),'2');
  assert.equal((await page.locator('#metric-pieces').innerText()).trim(),'130');
  assert.match(await money('consumption'),/612,68/);
  assert.match(await money('purchase'),/534,00/);
  assert.equal(await page.locator('#plan-rows tr').count(),4);
  assert.equal(await page.locator('#purchase-rows tr').count(),4);
  assert.match(await page.locator('#purchase-rows').innerText(),/9.051 g/);
  assert.match(await page.locator('#purchase-rows').innerText(),/5.249 g/);
  assert.match(await page.locator('#purchase-rows').innerText(),/9.000 g/);
  assert.match(await page.locator('#purchase-rows').innerText(),/7.000 cm/);
  assert.match(await page.locator('#purchase-rows').innerText(),/162,00/);
  await tab('models').click();
  assert.equal(await page.locator('#model-breakdown .group').count(),2);
  assert.match(await page.locator('#model-breakdown').innerText(),/Camisola Melina/);
  assert.match(await page.locator('#model-breakdown').innerText(),/Calcinha Tammy/);
  assert.match(await page.locator('#model-breakdown').innerText(),/510,95/);
  await tab('plan').click();
  await page.locator('#plan-model').selectOption('paula');
  await page.locator('#plan-size').selectOption('G');
  await page.locator('#plan-qty').fill('10');
  await page.locator('#plan-form button[type="submit"]').click();
  assert.equal((await page.locator('#metric-models').innerText()).trim(),'3');
  assert.equal((await page.locator('#metric-pieces').innerText()).trim(),'140');
  assert.equal(await page.locator('#plan-rows tr').count(),5);
  await page.locator('#plan-qty').fill('5');
  await page.locator('#plan-form button[type="submit"]').click();
  assert.equal(await page.locator('#plan-rows tr').count(),5,'repeated model and size must merge');
  assert.equal((await page.locator('#metric-pieces').innerText()).trim(),'145');
  // Edicao funciona tanto pela tabela desktop quanto pelos cartões mobile.
  const edit=page.locator(width<=940?'#plan-cards input[data-edit="paula|G"]':'#plan-rows input[data-edit="paula|G"]');
  await edit.fill('12');await edit.dispatchEvent('change');
  assert.equal((await page.locator('#metric-pieces').innerText()).trim(),'142');
  const remove=page.locator(width<=940?'#plan-cards button[data-remove="paula|G"]':'#plan-rows button[data-remove="paula|G"]');
  await remove.click();
  assert.equal((await page.locator('#metric-pieces').innerText()).trim(),'130');
  assert.equal(await page.locator('#plan-rows tr').count(),4);
  await page.locator('#plan-qty').fill('0');
  await page.locator('#plan-form button[type="submit"]').click();
  assert.match(await page.locator('#plan-message').innerText(),/permitido de 1 a 100000/);
  assert.equal((await page.locator('#metric-pieces').innerText()).trim(),'130');

  await tab('bom').click();
  await page.locator('#bom-model').selectOption('tammy');
  await page.locator('#bom-size').selectOption('M');
  await page.locator('#bom-material').selectOption('renda');
  assert.equal(await page.locator('#bom-qty').inputValue(),'42');
  await page.locator('#bom-qty').fill('52');
  await page.locator('#bom-form button[type="submit"]').click();
  assert.match(await page.locator('#bom-message').innerText(),/52 g por peça/);
  await tab('plan').click();
  assert.match(await page.locator('#purchase-rows').innerText(),/5.573 g/);
  assert.match(await page.locator('#purchase-rows').innerText(),/5.500 g/);
  assert.match(await money('purchase'),/555,00/);
  assert.match(await money('consumption'),/626,29/);

  await tab('materials').click();
  await page.locator('#material-id').selectOption('renda');
  assert.equal(await page.locator('#material-price').inputValue(),'42,00');
  await page.locator('#material-price').fill('50,00');
  await page.locator('#material-stock').fill('6000');
  await page.locator('#material-waste').fill('10');
  await page.locator('#material-pack').fill('1000');
  await page.locator('#materials-form button[type="submit"]').click();
  assert.match(await page.locator('#material-message').innerText(),/atualizados/);
  await tab('plan').click();
  assert.match(await money('purchase'),/324,00/);
  const list=await page.locator('#purchase-rows').innerText();
  assert.match(list,/5.676 g/);
  assert.match(list,/6.000 g/);
  assert.match(list,/0 g/);
  const [jsonDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#download-json').click()]);
  assert.equal(jsonDownload.suggestedFilename(),'HLGB-EVOLUCAO-PLANEJAMENTO-FICTICIO.json');
  const data=JSON.parse(fs.readFileSync(await jsonDownload.path(),'utf8'));
  assert.equal(data.schema,'hlgb-evolucao-planejamento-compras-v1');
  assert.equal(data.environment,'offline-demo');
  assert.equal(data.productionApproval,false);
  assert.equal(data.savedToDatabase,false);
  assert.equal(data.summary.pieces,130);
  assert.equal(data.summary.models,2);
  assert.equal(data.summary.purchaseCostCents,32400);
  assert.equal(data.byMaterial.find(m=>m.id==='renda').needed,5676);
  assert.equal(data.byMaterial.find(m=>m.id==='renda').toBuy,0);
  assert.equal(data.perModel.reduce((v,m)=>v+m.cost,0),data.summary.consumptionCostCents);
  assert(Object.values(data.checks).every(Boolean),'invariant failures: '+JSON.stringify(data.checks));
  const [csvDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#download-csv').click()]);
  assert.match(csvDownload.suggestedFilename(),/LISTA-COMPRAS-FICTICIA\.csv/);
  const csv=fs.readFileSync(await csvDownload.path(),'utf8');
  assert.match(csv,/Material;|Material"/);
  assert.match(csv,/Renda/);
  assert.match(csv,/Tule/);
  assert.match(csv,/32400|16200/);
  await page.locator('#reset-demo').click();
  assert.equal((await page.locator('#metric-pieces').innerText()).trim(),'130');
  assert.match(await money('purchase'),/534,00/);
  assert.match(await money('consumption'),/612,68/);
  const dims=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert(dims.scroll<=dims.width+2,'horizontal overflow '+width+'px '+JSON.stringify(dims));
  assert.deepEqual(errors,[],'no browser script failures');
  assert.deepEqual(requests,[],'no external requests');
  if(width===375){fs.mkdirSync(out,{recursive:true});await page.screenshot({path:path.join(out,'planejador-'+engine.name()+'-'+width+'.png'),fullPage:true})}
  console.log('PASS planejador '+engine.name()+' '+width+'px: grade, BOM, stock, loss, models, purchase, export, mobile');
 }finally{await page.close()}
}
(async()=>{const b=await engine.launch({headless:true});try{for(const w of [320,375,390,768,1280])await run(b,w)}finally{await b.close()}})().catch(e=>{console.error(e);process.exitCode=1});
