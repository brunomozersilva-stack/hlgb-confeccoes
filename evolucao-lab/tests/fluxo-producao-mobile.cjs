'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url'),{chromium,webkit}=require('playwright');
const engine=process.env.HLGB_BROWSER==='webkit'?webkit:chromium;
const fileUrl=pathToFileURL(path.resolve(__dirname,'../fluxo-producao-integrado.html')).href;
const screenshots=process.env.HLGB_SCREENSHOT_DIR||'/tmp/hlgb-producao';
async function testFlow(browser,width){
 const page=await browser.newPage({viewport:{width,height:820},deviceScaleFactor:1,acceptDownloads:true});
 const errors=[],requests=[];
 page.on('pageerror',e=>errors.push(String(e.message||e)));
 page.on('request',r=>{if(/^https?:/i.test(r.url()))requests.push(r.url())});
 const button=(stage,id)=>{
  const host=width<=920?'#grade-mobile':'#grade-body';
  return page.locator(host+' button[data-action="'+stage+'"][data-line="'+id+'"]').first();
 };
 const tab=stage=>page.locator('[data-stage="'+stage+'"]');
 try{
  await page.goto(fileUrl,{waitUntil:'load'});
  for(const [field,total] of Object.entries({ordered:'390',cut:'200',sent:'160',returned:'130',separated:'70'}))
   assert.equal((await page.locator('#metric-'+field).innerText()).trim(),total,field);
  assert.equal(await page.locator('#grade-body tr').count(),14);
  await page.locator('#search-order').fill('Leidiane Preto M');
  assert.equal(await page.locator('#grade-body tr').count(),1);
  await page.locator('#clear-filters').click();
  assert.equal(await page.locator('#grade-body tr').count(),14);
  await tab('send').click();
  assert.equal(await button('send','PD-100-L1').isDisabled(),true,'no sending before cut');
  await tab('cut').click();
  await button('cut','PD-100-L1').click();
  assert.match(await page.locator('#movement-context').innerText(),/20 peças/);
  await page.locator('#movement-qty').fill('21');
  assert.equal(await page.locator('#movement-confirm').isDisabled(),true,'cannot overcut');
  await page.locator('#movement-qty').fill('20');
  assert.equal(await page.locator('#movement-confirm').isDisabled(),true,'cut requires material worksheet');
  await page.locator('#movement-material').selectOption('tule');
  await page.locator('#movement-weight-total').fill('500');
  await page.locator('#movement-weight-used').fill('470');
  await page.locator('#movement-weight-waste').fill('50');
  assert.equal(await page.locator('#movement-confirm').isDisabled(),true,'material balance must match supplied weight');
  await page.locator('#movement-weight-used').fill('420');
  await page.locator('#movement-reviewer-two').selectOption('Conferente Demo A');
  assert.equal(await page.locator('#movement-confirm').isDisabled(),true,'two independent confirmations required');
  await page.locator('#movement-reviewer-two').selectOption('Conferente Demo B');
  assert.equal(await page.locator('#movement-confirm').isDisabled(),false);
  assert.match(await page.locator('#movement-preview').innerText(),/8,46/);
  await page.locator('#movement-confirm').click();
  assert.match(await page.locator('#cut-stats').innerText(),/500 g/);
  assert.match(await page.locator('#cut-stats').innerText(),/420 g/);
  assert.match(await page.locator('#cut-stats').innerText(),/50 g/);
  assert.match(await page.locator('#cut-stats').innerText(),/30 g/);
  assert.match(await page.locator('#cut-stats').innerText(),/8,46/);
  assert.match(await page.locator('#cut-material-rows').innerText(),/Camisola Melina.*Tule/);
  assert.equal((await page.locator('#metric-cut').innerText()).trim(),'220');
  assert.equal(await button('cut','PD-100-L1').isDisabled(),true,'same grade cannot be cut twice');
  await tab('send').click();
  await button('send','PD-100-L1').click();
  await page.locator('#movement-operator').selectOption('Fran Demo');
  await page.locator('#movement-qty').fill('20');
  await page.locator('#movement-confirm').click();
  assert.equal((await page.locator('#metric-sent').innerText()).trim(),'180');
  await tab('return').click();
  assert.equal(await button('return','PD-100-L2').isDisabled(),true,'no return before sending');
  await button('return','PD-100-L1').click();
  assert.equal(await page.locator('#movement-operator').inputValue(),'Fran Demo','return linked to facção selected when sent');
  await page.locator('#movement-qty').fill('21');
  assert.equal(await page.locator('#movement-confirm').isDisabled(),true,'no overreturn');
  await page.locator('#movement-qty').fill('18');
  await page.locator('#movement-confirm').click();
  assert.equal((await page.locator('#metric-returned').innerText()).trim(),'148');
  await tab('separate').click();
  assert.equal(await button('separate','PD-100-L2').isDisabled(),true,'no separation before return');
  await button('separate','PD-100-L1').click();
  await page.locator('#movement-qty').fill('19');
  assert.equal(await page.locator('#movement-confirm').isDisabled(),true,'no over-separation');
  await page.locator('#movement-qty').fill('10');
  await page.locator('#movement-confirm').click();
  assert.equal((await page.locator('#metric-separated').innerText()).trim(),'80');
  await button('separate','PD-100-L1').click();
  await page.locator('#movement-qty').fill('8');
  await page.locator('#movement-confirm').click();
  assert.equal(await button('separate','PD-100-L1').isDisabled(),true,'cannot separate returned twice');
  assert.equal((await page.locator('#metric-separated').innerText()).trim(),'88');
  await tab('audit').click();
  assert.equal(await page.locator('#audit-list .audit-item').count(),5);
  assert.match(await page.locator('#audit-status').innerText(),/9\/9 verificações/);
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#download-evidence').click()]);
  const report=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
  assert.equal(report.schema,'hlgb-evolucao-fluxo-producao-v1');
  assert.equal(report.environment,'offline-demo');
  assert.equal(report.fictitious,true);assert.equal(report.productionApproval,false);
  assert.equal(report.orders.length,4);assert.equal(report.movements.length,5);
  assert.deepEqual(report.materialSummary.totals,{gross:500,used:420,waste:50,leftover:30,cost:846,pieces:20});
  assert.equal(report.materialSummary.groups.length,1);
  assert.equal(report.materialSummary.groups[0].model,'Camisola Melina');
  assert.equal(report.movements[0].cutSheet.material,'tule');
  assert.equal(report.movements[0].cutSheet.spreader,'Infestador Demo A');
  assert.equal(report.movements[0].cutSheet.reviewerOne,'Conferente Demo A');
  assert.equal(report.movements[0].cutSheet.reviewerTwo,'Conferente Demo B');
  assert.deepEqual(report.counts,{ordered:390,cut:220,sent:180,returned:148,separated:88});
  assert(Object.values(report.checks).every(Boolean),JSON.stringify(report.checks));
  const order=report.orders.find(x=>x.id==='PD-100');
  assert.deepEqual([order.lines[0].ordered,order.lines[0].cut,order.lines[0].sent,order.lines[0].returned,order.lines[0].separated],[20,20,20,18,18]);
  assert.equal(order.lines[0].faction,'Fran Demo');
  assert.deepEqual(report.movements.map(x=>x.stage),['cut','send','return','separate','separate']);
  assert.equal(new Set(report.movements.map(x=>x.id)).size,5);
  await page.locator('#audit-reset').click();
  assert.equal((await page.locator('#metric-cut').innerText()).trim(),'200');
  assert.equal((await page.locator('#metric-separated').innerText()).trim(),'70');
  assert.equal(await page.locator('#audit-list .audit-item').count(),0);
  const dims=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert(dims.scroll<=dims.width+2,'horizontal overflow '+width+': '+JSON.stringify(dims));
  assert.deepEqual(errors,[],'no uncaught JavaScript errors');
  assert.deepEqual(requests,[],'offline only');
  if(width===375){fs.mkdirSync(screenshots,{recursive:true});await page.screenshot({path:path.join(screenshots,'producao-'+engine.name()+'-'+width+'.png'),fullPage:true})}
  console.log('PASS fluxo 5 etapas '+engine.name()+' '+width+'px: grade, bloqueios, auditoria, reset e sem rede');
 }finally{await page.close()}
}
(async()=>{const b=await engine.launch({headless:true});try{for(const w of [320,375,390,768,1280])await testFlow(b,w)}finally{await b.close()}})().catch(e=>{console.error(e);process.exitCode=1});
